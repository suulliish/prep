const T = (kz, ru) => ({ kz, ru });
/** Число m · 10^−p строкой: «4,07», «320». p может быть отрицательным (сдвиг влево от целого). */
const F = (m, p) => (p <= 0 ? String(m * 10 ** -p) : num(m / 10 ** p));
/** Строка ровно с p цифрами после запятой (для «0,50», «3,40» в сравнении и решениях). */
const pad = (m, p) => { const s = String(m).padStart(p + 1, '0'); return p ? `${s.slice(0, -p)},${s.slice(-p)}` : s; };
/** Целое m без нулей на конце (чтобы у числа было ровно p значащих знаков после запятой). */
const noTail = (r, lo, hi) => { let m; do m = r.int(lo, hi); while (m % 10 === 0); return m; };
const P10 = [1, 10, 100, 1000];

