// Тізбектің келесі мүшесі: тұрақты айырма, айырмалардың тұрақты айырмасы, екі қатар кезектесуі, еселі өсу. Бірнеше заңдылық
// әртүрлі жауап берсе, мини-ойын сол тізбекті алмайды.
const isAP = a => a.length >= 2 && a.every((x, i) => i === 0 || x - a[i - 1] === a[1] - a[0]);
const diffs = a => a.slice(1).map((x, i) => x - a[i]);
function nextValues(t) {
  const out = new Set(), L = t.length, last = t[L - 1];
  if (isAP(t)) out.add(last + (t[1] - t[0]));
  const d = diffs(t);
  if (L >= 5 && !isAP(t) && isAP(d)) out.add(last + d[d.length - 1] + (d[1] - d[0]));
  if (L >= 6) {
    const ev = t.filter((_, i) => i % 2 === 0), od = t.filter((_, i) => i % 2 === 1);
    if (ev.length >= 3 && od.length >= 3 && isAP(ev) && isAP(od)) { const nxt = L % 2 === 0 ? ev : od; out.add(nxt[nxt.length - 1] + (nxt[1] - nxt[0])); }
  }
  if (L >= 4 && t[0] > 0 && t[1] % t[0] === 0 && t[1] / t[0] >= 2 && t.every((x, i) => i === 0 || x === t[i - 1] * (t[1] / t[0]))) out.add(last * (t[1] / t[0]));
  return out;
}

