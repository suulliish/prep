const fact = n => (n <= 1 ? 1 : n * fact(n - 1));
const perm = (n, k) => { let x = 1; for (let i = 0; i < k; i++) x *= n - i; return x; };
const pairs = n => (n * (n - 1)) / 2;
const sumSq = n => { let s = 0; for (let k = 1; k <= n; k++) s += k * k; return s; };
const cntSide = (w, h, s) => (w - s + 1) * (h - s + 1);
const allSq = (w, h) => { let s = 0; for (let k = 1; k <= Math.min(w, h); k++) s += cntSide(w, h, k); return s; };

