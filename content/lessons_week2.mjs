// Казахский — черновик, нужна проверка носителем.

const gcd = (a, b) => (b ? gcd(b, a % b) : a);
const lcm = (a, b) => (a / gcd(a, b)) * b;
const factor = n => { const f = []; for (let p = 2; p * p <= n; p++) while (n % p === 0) { f.push(p); n /= p; } if (n > 1) f.push(n); return f; };
const isPrime = n => n > 1 && factor(n).length === 1;
const sup = k => String(k).split('').map(c => '⁰¹²³⁴⁵⁶⁷⁸⁹'[+c]).join('');
const powStr = f => { const c = {}; f.forEach(p => (c[p] = (c[p] || 0) + 1)); return Object.keys(c).map(Number).sort((a, b) => a - b).map(p => (c[p] > 1 ? `${p}${sup(c[p])}` : `${p}`)).join(' · '); };
function mc(r, right, wrong) {
  const all = [...new Set([right, ...wrong.filter(w => w !== right)])].slice(0, 4);
  const order = r.shuffle(all.map((_, k) => k));
  return { choices: order.map(k => all[k]), answer: order.indexOf(0) };
}

