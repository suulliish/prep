function mc(r, right, wrong) {
  const all = [...new Set([right, ...wrong.filter(w => w !== right)])].slice(0, 4);
  const order = r.shuffle(all.map((_, k) => k));
  return { choices: order.map(k => all[k]), answer: order.indexOf(0) };
}
// варианты — целые неотрицательные и не равные верному; max — наибольшая допустимая цифра/значение
const ints = (right, arr, max = 999) => [...new Set(arr.filter(v => Number.isInteger(v) && v >= 0 && v <= max && v !== right))].map(String);
const weighted = (r, groups) => { const tot = groups.reduce((a, g) => a + g[0], 0); let x = r.next() * tot; for (const [w, list] of groups) { if ((x -= w) < 0) return r.pick(list); } return r.pick(groups[0][1]); };

