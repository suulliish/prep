/** Один раунд мини-игры из ребуса: короткий вопрос и 3–4 варианта. */
function round(r, p) {
  const eq = `${p.words.join(' + ')} = ${p.sum}`, v = p.v;
  const top = p.target.kind === 'sum' ? 18 : 9;
  const others = p.target.kind === 'letter' ? p.letters.filter(l => l !== p.target.l).map(l => p.sols[0][l]) : [];
  const wrong = ints(v, [v + 1, v - 1, 0, 2, ...others, 9, 5, 8], top);
  const q = p.target.kind === 'sum' ? `${eq}. ${p.target.x} + ${p.target.y} = ?` : `${eq}. ${p.target.l} = ?`;
  return { q, ...mc(r, String(v), r.shuffle(wrong)) };
}
