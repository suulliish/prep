function mc(r, right, wrong) {
  const all = [...new Set([right, ...wrong.filter(w => w !== right)])].slice(0, 4);
  const order = r.shuffle(all.map((_, k) => k));
  return { choices: order.map(k => all[k]), answer: order.indexOf(0) };
}
// варианты — натуральные числа (> 0), не равные верному
const ints = (right, arr) => [...new Set(arr.filter(v => Number.isInteger(v) && v > 0 && v !== right))].map(String);
/** Строки-выражения ловушек, не равные верному выражению (по отпечатку). */
const exprs = (correct, traps) => [...new Set(traps.filter(t => sig(t.f) !== sig(correct.f)).map(t => t.s))];

