import { gcd, lcm, abl, dat } from './templates/lib.mjs';

function mc(r, right, wrong) {
  const all = [...new Set([right, ...wrong.filter(w => w !== right)])].slice(0, 4);
  const order = r.shuffle(all.map((_, k) => k));
  return { choices: order.map(k => all[k]), answer: order.indexOf(0) };
}
// дробь как текст, сокращённая («8/10» → «4/5»); целое — без знаменателя
const red = (n, d) => { const k = gcd(n, d) || 1; return [n / k, d / k]; };
const fs = (n, d) => { const [a, b] = red(n, d); return b === 1 ? String(a) : `${a}/${b}`; };
// ключ значения варианта: «1/2» и «2/4» — один ключ; неразборчивое — как строка
const vk = s => {
  let m;
  if ((m = /^(\d+)\/(\d+)$/.exec(s))) return red(+m[1], +m[2]).join('/');
  if (/^\d+$/.test(s)) return s + '/1';
  return 's:' + s;
};
// как mc, но неправильные варианты не должны совпадать по значению с верным и друг с другом
function mcv(r, right, wrong) {
  const seen = new Set([vk(right)]), out = [right];
  for (const w of r.shuffle(wrong.filter(x => x != null))) {
    const k = vk(w);
    if (seen.has(k)) continue;
    seen.add(k); out.push(w);
    if (out.length === 4) break;
  }
  const order = r.shuffle(out.map((_, k) => k));
  return { choices: order.map(k => out[k]), answer: order.indexOf(0) };
}
// целые варианты: только положительные и не равные верному
const ints = (right, list) => list.filter(v => Number.isInteger(v) && v > 0 && v !== right).map(String);
// число цифр, нужное для нумерации страниц 1…P
const digits = P => { let d = 0; for (let i = 1; i <= P; i++) d += String(i).length; return d; };

