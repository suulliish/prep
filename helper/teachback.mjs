/** Схема ответа для Gemini (responseSchema): формат держит сама модель, разбор ниже — вторая линия защиты. */
export const TEACH_SCHEMA = {
  type: 'OBJECT',
  properties: {
    verdict: { type: 'STRING', enum: VERDICTS },
    reply: { type: 'STRING' },
    followup: { type: 'STRING', nullable: true },
  },
  required: ['verdict', 'reply'],
};

/** Сообщения для модели: контекст + вопрос Бита + прошлый круг + ответ ребёнка. */
export function teachPrompt(b) {
  const t = b.topic || {};
  const round = roundOf(b);
  const ctx = [
    `ТЕМА: ${clip(t.title, 200)}${t.skill ? ` (${clip(t.skill, 60)})` : ''}`,
    `ПРАВИЛО ТЕМЫ (эталон; ребёнок его читал): ${clip(b.rule, 1500)}`,
    b.rule.includes('▢') ? 'В правиле есть закрытое число ▢: ребёнок находит его сам. Не называй его и не вычисляй.' : '',
    Array.isArray(b.examples) && b.examples.length ? `ПРИМЕРЫ ИЗ УРОКА (ребёнок их видел):\n${b.examples.slice(0, 3).map((x, i) => `${i + 1}) ${clip(x, 300)}`).join('\n')}` : '',
    `ВОПРОС, который ты задал ребёнку: ${clip(b.question, 300)}`,
    `РАУНД: ${round} из ${MAX_ROUNDS}${round >= MAX_ROUNDS ? ' (последний: followup = null, дай итог)' : ''}`,
  ].filter(Boolean).join('\n');
  const contents = [{ role: 'user', parts: [{ text: ctx + '\n\nСейчас ребёнок отвечает тебе.' }] }];
  for (const turn of (Array.isArray(b.history) ? b.history : []).slice(-4)) {
    const bit = turn?.role === 'bit';
    contents.push({ role: bit ? 'model' : 'user', parts: [{ text: bit ? clip(turn.text, 600) : `Ответ ребёнка: «${clip(turn.text, 400)}»` }] });
  }
  contents.push({ role: 'user', parts: [{ text: `Ответ ребёнка: «${clip(b.answer, 400)}»\nОцени по правилу и верни JSON.` }] });
  return contents;
}

/** Разбор ответа модели: {verdict, reply, followup} или null, если формат или длина не годятся. */
export function parseTeach(text, round = 1) {
  let o;
  try { o = JSON.parse(String(text).replace(/^```(?:json)?\s*|\s*```$/g, '').trim()); } catch { return null; }
  if (!o || typeof o !== 'object' || !VERDICTS.includes(o.verdict)) return null;
  const reply = typeof o.reply === 'string' ? o.reply.trim() : '';
  if (!reply) return null;
  let followup = typeof o.followup === 'string' && o.followup.trim() ? o.followup.trim() : null;
  // после «понял» и в последнем раунде вопроса быть не должно
  if (o.verdict === 'got' || round >= MAX_ROUNDS) followup = null;
  if (words(reply) + words(followup) > MAX_WORDS) return null;
  return { verdict: o.verdict, reply, followup };
}
