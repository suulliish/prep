/** Сообщения для модели: шаг + до 3 прошлых уточнений + вопрос ребёнка. */
export function lessonPrompt(b) {
  const s = b.step, t = b.topic || {};
  const lines = (Array.isArray(s.lines) ? s.lines : []).slice(0, 12).map(x => clip(x, 400));
  const choices = (Array.isArray(s.choices) ? s.choices : []).slice(0, 5);
  const shown = [s.text, ...lines].join(' ');
  const out = [
    `ТЕМА: ${clip(t.title, 200)}${t.skill ? ` (${clip(t.skill, 60)})` : ''}`,
    `ТИП ШАГА: ${KIND[s.type]}`,
    `ТЕКСТ ШАГА (как его видит ребёнок): ${clip(s.text, 1500)}`,
    lines.length ? `НА ЭКРАНЕ:\n${lines.map((x, i) => `${i + 1}) ${x}`).join('\n')}` : '',
    choices.length ? `ВАРИАНТЫ: ${choices.map((c, i) => `${'ABCDE'[i]}) ${clip(c, 120)}`).join('  ')}` : '',
    shown.includes('▢') ? 'В шаге есть закрытое число ▢: ребёнок должен вспомнить его сам. Не называй его и не вычисляй.' : '',
    b.rule ? `ПРАВИЛО ТЕМЫ (ребёнок его уже читал): ${clip(b.rule, 600)}` : '',
  ];
  if (s.answered === true) {
    if (s.picked != null) out.push(`ОТВЕТ РЕБЁНКА: ${clip(s.picked, 200)}${s.correct != null ? (s.picked === s.correct ? ' (верно)' : ' (неверно)') : ''}`);
    if (s.correct != null) out.push(`ВЕРНЫЙ ОТВЕТ (уже показан ребёнку): ${clip(s.correct, 200)}`);
    if (s.reveal) out.push(`РАЗБОР ИЗ УРОКА (ребёнок его видел): ${clip(s.reveal, 1200)}`);
  } else if (choices.length) {
    out.push('РЕБЁНОК ЕЩЁ НЕ ОТВЕТИЛ на вопрос шага: не говори, какой вариант верный, и не подводи к нему.');
  }
  const contents = [{ role: 'user', parts: [{ text: out.filter(Boolean).join('\n') + '\n\nРебёнок нажал «түсінбедім». Объясни этот шаг иначе.' }] }];
  for (const turn of (b.history || []).slice(-6)) {
    contents.push({ role: turn.role === 'bit' ? 'model' : 'user', parts: [{ text: clip(turn.text, 600) }] });
  }
  if (b.question) contents.push({ role: 'user', parts: [{ text: `Вопрос ученика: ${clip(b.question, 400)}` }] });
  return contents;
}
