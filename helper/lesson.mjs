// Чистые функции без сети и без зависимостей: проверка тела запроса и сборка промпта — их гоняют тесты.
// Сервер получает шаг ТАК, КАК ЕГО ВИДИТ РЕБЁНОК: закрытое число приходит как «▢», настоящего значения у сервера нет.

export const LESSON_TYPES = ['example', 'why', 'rule', 'predict', 'faded', 'blitz', 'final'];
// шаги, где ребёнок что-то решает сам: помощь только после ответа (как в практике, PNAS Bastani 2025)
export const ANSWER_FIRST = ['predict', 'faded', 'blitz', 'final'];

const clip = (s, n) => String(s ?? '').slice(0, n);

/** Код ошибки 400 или null, если запрос урока годится. */
export function checkLesson(b) {
  const s = b?.step;
  if (!s || typeof s !== 'object') return 'no_step';
  if (!LESSON_TYPES.includes(s.type)) return 'bad_step';
  if (!s.text || typeof s.text !== 'string') return 'no_step';
  if (ANSWER_FIRST.includes(s.type) && s.answered !== true) return 'answer_first';
  return null;
}

