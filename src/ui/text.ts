// Мелкие помощники для текста на экранах.

/** Неразрывные пробелы внутри чисел: «648 210 060» не рвётся посреди записи на двух строках.
 *  Пробел между цифрами (разряды и классы), перед «%» и между «қалдық» и числом заменяется на U+00A0. */
export const nb = (s: string): string => s
  .replace(/(\d) (?=\d)/g, '$1\u00A0')
  .replace(/(\d) (?=[%°])/g, '$1\u00A0')
  .replace(/(қалдық) (?=\d)/gi, '$1\u00A0');

/** Длина самой длинной «неразрывной» части: по ней выбирают размер шрифта и число колонок плиток ответов. */
export const longestChunk = (s: string): number => Math.max(0, ...nb(s).split(/[ \n]+/).map(w => w.length));
