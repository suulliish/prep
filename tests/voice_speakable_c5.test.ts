// Озвучка аварийных уроков (C5): порядковые числительные с суффиксом, градусы, неизвестное внутри фразы.
import { describe, it, expect } from 'vitest';
// @ts-ignore
import { speakable } from '../scripts/voice/lesson-lines.mjs';

describe('speakable: числа и знаки аварийных уроков', () => {
  it('«35-ші», «30-шы», «28-ші» читаются одним порядковым словом, суффикс не удваивается', () => {
    expect(speakable('35-ші цифр')).toBe('отыз бесінші цифр');
    expect(speakable('28-ші орын')).toBe('жиырма сегізінші орын');
    expect(speakable('30-шы орын')).toBe('отызыншы орын');
    expect(speakable('1-қадам')).toBe('бірінші қадам');   // прежнее правило не сломано
  });
  it('градус и неизвестное внутри фразы не остаются знаками для озвучки', () => {
    expect(speakable('Бұрыш 30° болады')).toBe('Бұрыш отыз градус болады');
    expect(speakable('0,5° минутына')).toContain('градус');
    expect(speakable('18 + ? = 81 болса')).not.toMatch(/\?|°/);
    expect(speakable('Неше болады?')).toBe('Неше болады?');   // вопросительный знак в конце фразы не трогаем
  });
});
